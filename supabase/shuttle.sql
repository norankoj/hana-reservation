create table if not exists public.shuttle_passengers (
  id       bigint generated always as identity primary key,
  seq      int not null unique,                                    -- 명단 번호 (가나다순)
  name     text not null,
  affil    text not null default '',                               -- 소속 (셀 번호. 가족은 동반자 이름)
  phone    text not null default '',
  route    text not null check (route in ('왕복', '출발만', '귀가만')),
  go_at    timestamptz,                                            -- 가는 편(출발) 탑승 체크 시각
  back_at  timestamptz                                             -- 오는 편(귀가) 탑승 체크 시각
);

alter table public.shuttle_passengers enable row level security;
-- 표 자체는 아무도 직접 못 읽습니다(연락처가 들어 있어서). 브라우저에는 아래 뷰만 열어 줍니다.

-- 화면에 보여 줄 것. 연락처는 빼고 이름·소속·탑승 시각만.
create or replace view public.shuttle_board as
  select id, seq, name, affil, route, go_at, back_at
    from public.shuttle_passengers;

grant select on public.shuttle_board to anon, authenticated;

-- 담당자용(/shuttle/check). 바로 전화할 수 있게 연락처까지. 주소를 아는 사람만 보게 되므로
-- 이 링크는 단체방에 올리지 말고 담당자에게만 보내세요.
create or replace view public.shuttle_roster as
  select id, seq, name, affil, phone, route, go_at, back_at
    from public.shuttle_passengers;

grant select on public.shuttle_roster to anon, authenticated;

-- 탑승 체크. 비밀번호 없이 링크(/shuttle/check)만으로 누를 수 있게,
-- 탑승 시각 두 칸만 고칠 수 있도록 열어 둡니다. 이름·연락처·명단은 고칠 수 없습니다.
grant update (go_at, back_at) on public.shuttle_passengers to anon, authenticated;

drop policy if exists "누구나 탑승 체크" on public.shuttle_passengers;
create policy "누구나 탑승 체크" on public.shuttle_passengers
  for update to anon, authenticated
  using (true) with check (true);

